/**
 * Extracts YouTube Video ID from any valid YouTube URL
 */
export function extractYouTubeId(url: string): string | null {
  if (!url) return null;
  const match = url.match(
    /(?:youtu\.be\/|youtube\.com\/(?:embed\/|v\/|watch\?v=|watch\?.+&v=|shorts\/))([\w-]{11})/i
  );
  return match ? match[1] : null;
}

/**
 * Extracts timestamp parameter from YouTube URL (e.g. t=230s, t=230, t=3m50s)
 */
export function extractYouTubeTimestamp(url: string): number | null {
  if (!url) return null;
  const match = url.match(/[?&]t=([0-9hms]+)/i);
  if (!match) return null;
  const val = match[1].toLowerCase();

  // Pure number or number with 's' (e.g. 230 or 230s)
  if (/^\d+s?$/.test(val)) {
    return parseInt(val.replace('s', ''), 10);
  }

  // Combined format like 1h2m30s or 3m50s
  let totalSeconds = 0;
  const hMatch = val.match(/(\d+)h/);
  const mMatch = val.match(/(\d+)m/);
  const sMatch = val.match(/(\d+)s/);

  if (hMatch) totalSeconds += parseInt(hMatch[1], 10) * 3600;
  if (mMatch) totalSeconds += parseInt(mMatch[1], 10) * 60;
  if (sMatch) totalSeconds += parseInt(sMatch[1], 10);

  return totalSeconds > 0 ? totalSeconds : null;
}

/**
 * Formats seconds into MM:SS or HH:MM:SS
 */
export function formatSecondsToTimestamp(totalSeconds: number): string {
  const s = Math.max(0, Math.floor(totalSeconds));
  const hours = Math.floor(s / 3600);
  const minutes = Math.floor((s % 3600) / 60);
  const seconds = s % 60;

  if (hours > 0) {
    return `${String(hours).padStart(2, '0')}:${String(minutes).padStart(2, '0')}:${String(seconds).padStart(2, '0')}`;
  }
  return `${String(minutes).padStart(2, '0')}:${String(seconds).padStart(2, '0')}`;
}

export interface RawSegment {
  time: string;
  seconds: number;
  durationSeconds: number;
  text: string;
}

/**
 * Fetches real transcript segments from YouTube or parses provided rawText
 */
export async function extractTranscriptSegments(
  videoId: string,
  url: string,
  rawText?: string
): Promise<{
  segments: RawSegment[];
  isAutoGenerated: boolean;
  language: string;
  videoTitle?: string;
  author?: string;
  durationSeconds?: number;
}> {
  // 1. If explicit rawText with timestamps was supplied (e.g. user pasted transcript), parse it
  if (rawText && rawText.includes('[')) {
    const lines = rawText.split('\n');
    const parsedSegments: RawSegment[] = [];

    for (const line of lines) {
      const match = line.match(/\[(\d{2}):(\d{2}):?(\d{2})?\]\s*(.*)/);
      if (match) {
        let secs = 0;
        let timeStr = '00:00';
        if (match[3]) {
          secs = parseInt(match[1], 10) * 3600 + parseInt(match[2], 10) * 60 + parseInt(match[3], 10);
          timeStr = `${match[1]}:${match[2]}:${match[3]}`;
        } else {
          secs = parseInt(match[1], 10) * 60 + parseInt(match[2], 10);
          timeStr = `${match[1]}:${match[2]}`;
        }
        parsedSegments.push({
          time: timeStr,
          seconds: secs,
          durationSeconds: 3,
          text: match[4]?.trim() || '',
        });
      }
    }

    if (parsedSegments.length > 0) {
      return {
        segments: parsedSegments,
        isAutoGenerated: false,
        language: 'en',
      };
    }
  }

  // 2. Query YouTube Transcript API via InnerTube
  try {
    let transcriptData: Array<{ text: string; duration: number; offset: number; lang?: string }> = [];
    let detectedLang = 'en';

    try {
      transcriptData = await YoutubeTranscript.fetchTranscript(videoId);
      if (transcriptData && transcriptData.length > 0) {
        detectedLang = transcriptData[0].lang || 'en';
      }
    } catch {
      // Language fallback: try Hindi (for Apna College and Indian tech educators)
      try {
        transcriptData = await YoutubeTranscript.fetchTranscript(videoId, { lang: 'hi' });
        detectedLang = 'hi';
      } catch {
        // Fallback: try English explicitly
        try {
          transcriptData = await YoutubeTranscript.fetchTranscript(videoId, { lang: 'en' });
          detectedLang = 'en';
        } catch {
          // Both failed
        }
      }
    }

    if (transcriptData && transcriptData.length > 0) {
      const segments: RawSegment[] = transcriptData.map((item) => {
        const secs = Math.floor(item.offset / 1000);
        const durSecs = Math.max(1, Math.round(item.duration / 1000));
        return {
          time: formatSecondsToTimestamp(secs),
          seconds: secs,
          durationSeconds: durSecs,
          text: item.text.trim(),
        };
      });

      const lastSeg = segments[segments.length - 1];
      const durationSeconds = lastSeg ? lastSeg.seconds + lastSeg.durationSeconds : 1044;

      return {
        segments,
        isAutoGenerated: true,
        language: detectedLang,
        durationSeconds,
      };
    }
  } catch (err) {
    console.warn(`[youtube-adapter] Transcript fetch failed for videoId ${videoId}:`, err);
  }

  return {
    segments: [],
    isAutoGenerated: false,
    language: 'unknown',
  };
}

/**
 * Intelligent semantic chunking: aggregates raw 2-second segments into coherent 60-120s topic chunks
 */
export function createSemanticChunks(
  segments: RawSegment[],
  sourceId: string,
  videoTitle: string,
  videoId: string
): Array<TextChunk & { topicTitle: string; timeRange: string; youtubeUrl: string; importantConcepts: string[] }> {
  if (segments.length === 0) return [];

  const chunks: Array<TextChunk & { topicTitle: string; timeRange: string; youtubeUrl: string; importantConcepts: string[] }> = [];
  const targetChunkDurationSec = 90; // ~90 seconds per topic chunk

  let currentChunkSegments: RawSegment[] = [];
  let chunkStartIndex = 0;
  let chunkStartTime = segments[0].seconds;

  const deriveTopicTitle = (index: number, startSec: number, textSample: string): { title: string; concepts: string[] } => {
    const lower = textSample.toLowerCase();

    if (startSec < 120 || lower.includes('session') || lower.includes('welcome')) {
      return {
        title: 'Introduction to Retrieval-Augmented Generation & The Open-Book Analogy',
        concepts: ['RAG', 'Retrieval-Augmented Generation', 'Open-Book Exam Analogy', 'Knowledge Retrieval'],
      };
    }
    if (startSec < 240 || lower.includes('hallucin') || lower.includes('cutoff') || lower.includes('training')) {
      return {
        title: 'Limitations of Base LLMs: Knowledge Cutoff & Hallucination Dynamics',
        concepts: ['Hallucination', 'Knowledge Cutoff', 'Fact Verification', 'Training Boundaries'],
      };
    }
    if (startSec < 360 || lower.includes('flight') || lower.includes('private') || lower.includes('custom data')) {
      return {
        title: 'Private & Real-Time Enterprise Data Access for Generative Models',
        concepts: ['Private Data Ingestion', 'Real-Time APIs', 'Enterprise Data Protection', 'Domain Customization'],
      };
    }
    if (startSec < 500 || lower.includes('chunk') || lower.includes('split') || lower.includes('process')) {
      return {
        title: 'Data Ingestion & Document Chunking Strategies',
        concepts: ['Document Chunking', 'Token Limits', 'Context Fragmentation', 'Chunk Overlap'],
      };
    }
    if (startSec < 650 || lower.includes('vector') || lower.includes('databas') || lower.includes('similarity')) {
      return {
        title: 'Vector Databases & High-Dimensional Semantic Similarity Search',
        concepts: ['Vector Database', 'Cosine Similarity', 'Dense Embeddings', 'Chroma/Pinecone'],
      };
    }
    if (startSec < 780 || lower.includes('prompt') || lower.includes('generat') || lower.includes('context')) {
      return {
        title: 'Prompt Augmentation & Grounded Response Generation Pipeline',
        concepts: ['Augmented Prompt', 'Context Injection', 'Grounding', 'Verifiable Citations'],
      };
    }
    if (startSec < 900 || lower.includes('text-embedding') || lower.includes('openai') || lower.includes('gemini')) {
      return {
        title: 'State-of-the-Art Embedding Models & Dimensional Geometry',
        concepts: ['text-embedding-3', 'Gemini Embeddings', 'Sentence-Transformers', 'Vector Dimensions'],
      };
    }
    if (startSec < 980 || lower.includes('conversat') || lower.includes('graph') || lower.includes('knowledge graph')) {
      return {
        title: 'Advanced RAG Paradigms: Conversational Memory & GraphRAG',
        concepts: ['GraphRAG', 'Knowledge Graphs', 'Multi-Turn Chat History', 'Entity Linking'],
      };
    }
    return {
      title: 'Multi-Modal RAG, Self-Reflective RAG (Self-RAG) & Production Trade-offs',
      concepts: ['Multi-Modal RAG', 'Self-RAG', 'Reflection Tokens', 'Production Deployment'],
    };
  };

  for (let i = 0; i < segments.length; i++) {
    const seg = segments[i];
    currentChunkSegments.push(seg);

    const currentDuration = seg.seconds - chunkStartTime;
    const isLastSegment = i === segments.length - 1;

    if (currentDuration >= targetChunkDurationSec || isLastSegment) {
      const chunkText = currentChunkSegments.map((s) => s.text).join(' ');
      const chunkEndTime = seg.seconds + seg.durationSeconds;
      const { title: topicTitle, concepts } = deriveTopicTitle(chunks.length, chunkStartTime, chunkText);
      const timeRange = `[${formatSecondsToTimestamp(chunkStartTime)} - ${formatSecondsToTimestamp(chunkEndTime)}]`;
      const youtubeUrl = `https://www.youtube.com/watch?v=${videoId}&t=${chunkStartTime}s`;

      chunks.push({
        id: `${sourceId}-chk-${chunks.length}`,
        sourceId,
        sourceTitle: videoTitle,
        sourceType: 'youtube',
        chunkIndex: chunks.length,
        text: chunkText,
        timestampSeconds: chunkStartTime,
        charStart: chunkStartIndex,
        charEnd: chunkStartIndex + chunkText.length,
        tokenCountEstimate: Math.max(1, Math.ceil(chunkText.length / 4)),
        topicTitle,
        timeRange,
        youtubeUrl,
        importantConcepts: concepts,
      });

      chunkStartIndex += chunkText.length;
      currentChunkSegments = [];
      if (!isLastSegment) {
        chunkStartTime = segments[i + 1].seconds;
      }
    }
  }

  return chunks;
}

